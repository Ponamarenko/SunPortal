package app.sunportal.model

/**
 * Коды погоды WMO → иконка и украинское описание.
 * Формат повторяет сервер SunPortal (`weather_read.php`), чтобы карточка погоды
 * выглядела одинаково независимо от источника (сервер или Open-Meteo).
 */
object WeatherCodes {
    /** Эмодзи-иконка по коду WMO. */
    fun icon(code: Int): String = when (code) {
        0 -> "☀️"
        1 -> "🌤"
        2 -> "⛅"
        3 -> "☁️"
        45, 48 -> "🌫"
        51, 53, 55 -> "🌦"
        56, 57 -> "🌧"
        61, 63, 65, 66, 67 -> "🌧"
        71, 73, 75, 77 -> "🌨"
        80, 81, 82 -> "🌧"
        85, 86 -> "🌨"
        95, 96, 99 -> "⛈"
        else -> "☁️"
    }

    /** Текст описания по коду WMO (укр.). */
    fun desc(code: Int): String = when (code) {
        0 -> "Ясно"
        1 -> "Переважно ясно"
        2 -> "Мінлива хмарність"
        3 -> "Хмарно"
        45 -> "Туман"
        48 -> "Паморозь"
        51 -> "Невелика мряка"
        53 -> "Мряка"
        55 -> "Сильна мряка"
        56 -> "Крижана мряка"
        57 -> "Сильна крижана мряка"
        61 -> "Невеликий дощ"
        63 -> "Дощ"
        65 -> "Сильний дощ"
        66 -> "Крижаний дощ"
        67 -> "Сильний крижаний дощ"
        71 -> "Невеликий сніг"
        73 -> "Сніг"
        75 -> "Сильний сніг"
        77 -> "Снігова крупа"
        80 -> "Невеликі зливи"
        81 -> "Зливи"
        82 -> "Сильні зливи"
        85 -> "Снігові зливи"
        86 -> "Сильні снігові зливи"
        95 -> "Гроза"
        96 -> "Гроза з градом"
        99 -> "Сильна гроза з градом"
        else -> "Немає даних"
    }
}
